    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked

    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow == -1) {
        return;
    }

    String supplierId =
            jTable1.getValueAt(selectedRow, 0).toString();

    String supplierName =
            jTable1.getValueAt(selectedRow, 1).toString();

    String contactPerson =
            jTable1.getValueAt(selectedRow, 2).toString();

    String phone =
            jTable1.getValueAt(selectedRow, 3).toString();

    String email =
            jTable1.getValueAt(selectedRow, 4).toString();

    String address =
            jTable1.getValueAt(selectedRow, 5).toString();

    SupplierForm form = new SupplierForm(
            supplierId,
            supplierName,
            contactPerson,
            phone,
            email,
            address
    );

    form.setVisible(true);

    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a supplier first!"
        );

        return;
    }

    String supplierId =
            jTable1.getValueAt(selectedRow, 0).toString();

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this supplier?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    try {

        java.sql.Connection con =
                com.mobilephoneshop.util.DBConnection.getConnection();

        String sql =
                "DELETE FROM suppliers WHERE supplier_id = ?";

        java.sql.PreparedStatement ps =
                con.prepareStatement(sql);

        ps.setInt(1, Integer.parseInt(supplierId));

        int result = ps.executeUpdate();

        if (result > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Supplier Deleted Successfully!"
            );

            // Refresh table
            javax.swing.table.DefaultTableModel model =
                    (javax.swing.table.DefaultTableModel) jTable1.getModel();

            model.removeRow(selectedRow);

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Supplier Not Found!"
            );
        }

        ps.close();
        con.close();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton2ActionPerformed

