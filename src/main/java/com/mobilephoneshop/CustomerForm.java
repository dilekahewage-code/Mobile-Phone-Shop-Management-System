    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

    String CustomerID = jTextField2.getText();        
    String firstName = jTextField7.getText();
    String lastName = jTextField3.getText();
    String phone = jTextField4.getText();
    String email = jTextField5.getText();
    String address = jTextField6.getText();

    String sql = "INSERT INTO customers "
            + "(customer_id, first_name, last_name, phone, email, address) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    java.sql.Connection con =
            com.mobilephoneshop.util.DBConnection.getConnection();

    java.sql.PreparedStatement ps =
            con.prepareStatement(sql);

    ps.setString(1, CustomerID);
    ps.setString(2, firstName);
    ps.setString(3, lastName);
    ps.setString(4, phone);
    ps.setString(5, email);
    ps.setString(6, address);

    ps.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Customer Saved Successfully!"
    );

    ps.close();
    con.close();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Save Failed!\n" + e.getMessage()
    );
}

    }//GEN-LAST:event_jButton2ActionPerformed

