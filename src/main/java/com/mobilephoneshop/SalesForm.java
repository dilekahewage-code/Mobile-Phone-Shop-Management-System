    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {

    String saleId = jTextField1.getText();
    String customerId = jTextField2.getText();
    String employeeId = jTextField3.getText();
    String saleDate = jTextField4.getText();
    String subtotal = jTextField5.getText();
    String discount = jTextField6.getText();
    String tax = jTextField7.getText();
    String total = jTextField8.getText();

    String sql = "UPDATE sales SET "
            + "customer_id = ?, "
            + "employee_id = ?, "
            + "sale_date = ?, "
            + "subtotal = ?, "
            + "discount = ?, "
            + "tax = ?, "
            + "total = ? "
            + "WHERE sale_id = ?";

    java.sql.Connection con =
            com.mobilephoneshop.util.DBConnection.getConnection();

    java.sql.PreparedStatement ps =
            con.prepareStatement(sql);

    ps.setInt(1, Integer.parseInt(customerId));
    ps.setInt(2, Integer.parseInt(employeeId));
    ps.setDate(3, java.sql.Date.valueOf(saleDate));
    ps.setDouble(4, Double.parseDouble(subtotal));
    ps.setDouble(5, Double.parseDouble(discount));
    ps.setDouble(6, Double.parseDouble(tax));
    ps.setDouble(7, Double.parseDouble(total));
    ps.setInt(8, Integer.parseInt(saleId));

    int result = ps.executeUpdate();

    if (result > 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Sale Updated Successfully!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Sale Not Found!"
        );
    }

    ps.close();
    con.close();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton3ActionPerformed

