    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       try {

    String customerId = jTextField3.getText();
    String employeeId = jTextField4.getText();
    String saleDate = jTextField5.getText();
    String subtotal = jTextField6.getText();
    String discount = jTextField7.getText();
    String tax = jTextField8.getText();
    String total = jTextField1.getText();

    String sql = "INSERT INTO sales "
            + "(customer_id, employee_id, sale_date, subtotal, discount, tax, total) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?)";

    java.sql.Connection con =
            com.mobilephoneshop.util.DBConnection.getConnection();

    java.sql.PreparedStatement ps =
            con.prepareStatement(sql);

    ps.setInt(1, Integer.parseInt(customerId));
    ps.setInt(2, Integer.parseInt(employeeId));
    ps.setDate(3, java.sql.Date.valueOf(saleDate));
    ps.setDouble(4, Double.parseDouble(subtotal));
    ps.setDouble(5, Double.parseDouble(discount));
    ps.setDouble(6, Double.parseDouble(tax));
    ps.setDouble(7, Double.parseDouble(total));

    ps.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Sale Saved Successfully!"
    );

    ps.close();
    con.close();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton2ActionPerformed

