    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {

    java.sql.Connection con =
            com.mobilephoneshop.util.DBConnection.getConnection();

    String sql = "SELECT customer_id, first_name, last_name, phone, email, address FROM customers";

    java.sql.PreparedStatement ps =
            con.prepareStatement(sql);

    java.sql.ResultSet rs =
            ps.executeQuery();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    while (rs.next()) {

        model.addRow(new Object[]{
            rs.getInt("customer_id"),
            rs.getString("first_name"),
            rs.getString("last_name"),
            rs.getString("phone"),
            rs.getString("email"),
            rs.getString("address")
        });
    }

    rs.close();
    ps.close();
    con.close();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a customer first!"
    );

    return;
}

int customerId = Integer.parseInt(
        jTable1.getValueAt(selectedRow, 0).toString()
);

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this customer?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm == javax.swing.JOptionPane.YES_OPTION) {

    try {

        java.sql.Connection con =
                com.mobilephoneshop.util.DBConnection.getConnection();

        String sql =
                "DELETE FROM customers WHERE customer_id = ?";

        java.sql.PreparedStatement ps =
                con.prepareStatement(sql);

        ps.setInt(1, customerId);

        int result = ps.executeUpdate();

        if (result > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Customer Deleted Successfully!"
            );

            // Refresh table
            jButton1.doClick();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Customer Not Found!"
            );
        }

        ps.close();
        con.close();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delete Failed!\n" + e.getMessage()
        );
    }
}
    }//GEN-LAST:event_jButton2ActionPerformed

