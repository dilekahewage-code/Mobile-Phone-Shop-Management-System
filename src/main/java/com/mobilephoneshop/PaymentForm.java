    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

    try {

        String paymentId = jTextField2.getText();
        String saleId = jTextField4.getText();
        String paymentMethod = jComboBox1.getSelectedItem().toString();
        String amount = jTextField5.getText();
        String paymentDate = jTextField3.getText();

        String sql = "UPDATE payments SET "
                + "sale_id = ?, "
                + "payment_method = ?, "
                + "amount = ? "
                + "WHERE payment_id = ?";

        java.sql.Connection con =
                com.mobilephoneshop.util.DBConnection.getConnection();

        java.sql.PreparedStatement ps =
                con.prepareStatement(sql);

        ps.setInt(1, Integer.parseInt(saleId));
        ps.setString(2, paymentMethod);
        ps.setDouble(3, Double.parseDouble(amount));
        ps.setInt(4, Integer.parseInt(paymentId));

        int result = ps.executeUpdate();

        if (result > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Payment Updated Successfully!"
            );

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Payment Not Found!"
            );
        }

        ps.close();
        con.close();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton3ActionPerformed

