    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

    String firstName = jTextField3.getText();
    String lastName = jTextField4.getText();
    String phone = jTextField5.getText();
    String email = jTextField6.getText();
    String position = jTextField8.getText();
    String salary = jTextField1.getText();

    String sql = "INSERT INTO employees "
            + "(first_name, last_name, phone, email, position, salary) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    java.sql.Connection con =
            com.mobilephoneshop.util.DBConnection.getConnection();

    java.sql.PreparedStatement ps =
            con.prepareStatement(sql);

    ps.setString(1, firstName);
    ps.setString(2, lastName);
    ps.setString(3, phone);
    ps.setString(4, email);
    ps.setString(5, position);
    ps.setDouble(6, Double.parseDouble(salary));

    int result = ps.executeUpdate();

    if (result > 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Employee Saved Successfully!"
        );
    }

    ps.close();
    con.close();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
       try {

    String employeeId = jTextField2.getText();
    String firstName = jTextField3.getText();
    String lastName = jTextField4.getText();
    String phone = jTextField5.getText();
    String email = jTextField6.getText();
    String position = jTextField8.getText();
    String salary = jTextField1.getText();

    String sql = "UPDATE employees SET "
            + "first_name = ?, "
            + "last_name = ?, "
            + "phone = ?, "
            + "email = ?, "
            + "position = ?, "
            + "salary = ? "
            + "WHERE employee_id = ?";

    java.sql.Connection con =
            com.mobilephoneshop.util.DBConnection.getConnection();

    java.sql.PreparedStatement ps =
            con.prepareStatement(sql);

    ps.setString(1, firstName);
    ps.setString(2, lastName);
    ps.setString(3, phone);
    ps.setString(4, email);
    ps.setString(5, position);
    ps.setDouble(6, Double.parseDouble(salary));
    ps.setInt(7, Integer.parseInt(employeeId));

    int result = ps.executeUpdate();

    if (result > 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Employee Updated Successfully!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Employee Not Found!"
        );
    }

    ps.close();
    con.close();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton3ActionPerformed

