    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

    try {

        java.sql.Connection con =
                com.mobilephoneshop.util.DBConnection.getConnection();

        String sql = "SELECT sale_id, customer_id, employee_id, "
                + "sale_date, subtotal, discount, tax, total "
                + "FROM sales ORDER BY sale_id";

        java.sql.PreparedStatement ps =
                con.prepareStatement(sql);

        java.sql.ResultSet rs =
                ps.executeQuery();

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("sale_id"),
                rs.getInt("customer_id"),
                rs.getInt("employee_id"),
                rs.getTimestamp("sale_date"),
                rs.getDouble("subtotal"),
                rs.getDouble("discount"),
                rs.getDouble("tax"),
                rs.getDouble("total")
            });
        }

        rs.close();
        ps.close();
        con.close();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a sale first!"
        );

        return;
    }

    int saleId = Integer.parseInt(
            jTable1.getValueAt(selectedRow, 0).toString()
    );

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete Sale ID " + saleId + "?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    try {

        java.sql.Connection con =
                com.mobilephoneshop.util.DBConnection.getConnection();

        String sql = "DELETE FROM sales WHERE sale_id = ?";

        java.sql.PreparedStatement ps =
                con.prepareStatement(sql);

        ps.setInt(1, saleId);

        int result = ps.executeUpdate();

        if (result > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Sale Deleted Successfully!"
            );

            // Refresh table
            jButton1ActionPerformed(null);

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Sale Not Found!"
            );
        }

        ps.close();
        con.close();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked

    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow == -1) {
        return;
    }

    String saleId =
            jTable1.getValueAt(selectedRow, 0).toString();

    String customerId =
            jTable1.getValueAt(selectedRow, 1).toString();

    String employeeId =
            jTable1.getValueAt(selectedRow, 2).toString();

    String saleDate =
            jTable1.getValueAt(selectedRow, 3).toString();

    String subtotal =
            jTable1.getValueAt(selectedRow, 4).toString();

    String discount =
            jTable1.getValueAt(selectedRow, 5).toString();

    String tax =
            jTable1.getValueAt(selectedRow, 6).toString();

    String total =
            jTable1.getValueAt(selectedRow, 7).toString();

    SalesForm form = new SalesForm(
            saleId,
            customerId,
            employeeId,
            saleDate,
            subtotal,
            discount,
            tax,
            total
    );

    form.setVisible(true);

    }//GEN-LAST:event_jTable1MouseClicked

