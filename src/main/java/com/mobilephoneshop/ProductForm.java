    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    try {

        String productName = txtProductName.getText();
        String brand = txtBrand.getText();
        String model = txtModel.getText();
        double price = Double.parseDouble(txtPrice.getText());
        int quantity = (Integer) spnQuantity.getValue();

        String category =
                cmbCategory.getSelectedItem().toString();

        int categoryId =
                Integer.parseInt(category.split(" - ")[0]);

        String supplier =
                cmbSupplier.getSelectedItem().toString();

        int supplierId =
                Integer.parseInt(supplier.split(" - ")[0]);

        String sql = "UPDATE products SET "
                + "price = ?, "
                + "quantity = ?, "
                + "category_id = ?, "
                + "supplier_id = ? "
                + "WHERE product_name = ? "
                + "AND brand = ? "
                + "AND model = ?";

        java.sql.Connection con =
                com.mobilephoneshop.util.DBConnection.getConnection();

        java.sql.PreparedStatement ps =
                con.prepareStatement(sql);

        ps.setDouble(1, price);
        ps.setInt(2, quantity);
        ps.setInt(3, categoryId);
        ps.setInt(4, supplierId);
        ps.setString(5, productName);
        ps.setString(6, brand);
        ps.setString(7, model);

        int result = ps.executeUpdate();

        if (result > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Product Updated Successfully!"
            );

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Product Not Found!"
            );
        }

        ps.close();
        con.close();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Update Failed: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_jButton1ActionPerformed

